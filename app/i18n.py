def t(key: str, lang: str = "en", **kwargs) -> str:
    """
    Return the translated string for the given key and language.

    Parameters
    ----------
    key : str
        Translation key from TRANSLATIONS dict.
    lang : str
        Language code: 'en' or 'es'.
    **kwargs
        Format arguments passed to str.format().

    Returns
    -------
    str
        Translated (and optionally formatted) string.
        Falls back to English if key or lang not found.
    """
    entry = TRANSLATIONS.get(key, {})
    text  = entry.get(lang) or entry.get("en") or key
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, ValueError):
            pass
    return text
